(function(){
  var ENG = window.LAEngine({ dicts: window.SITE_I18N });
  var CUR = 'ar';
  window.setSiteLang = function(l){
    CUR = (l==='en'||l==='fr') ? l : 'ar';
    ENG.apply(CUR);
    var wrap = document.getElementById('langBtns');
    if(wrap) Array.prototype.forEach.call(wrap.querySelectorAll('button'),function(b){
      b.classList.toggle('active', b.getAttribute('data-lang')===CUR);
    });
    try{ localStorage.setItem('la_site_lang', CUR); }catch(e){}
  };
  // النصوص الجديدة بتترجم لحالها — هالدالة باقية للتوافق مع الصفحات
  window.siteRelang = function(){ ENG.relang(); };
  // ترجمة محتوى جاي من قاعدة البيانات (أسماء الباقات وميزاتها)
  window.siteLearn = function(ar, en, fr){ if(ar) ENG.learn(ar, { en: en, fr: fr || en }); };
  window.siteT = function(ar){ return ENG.t(ar); };
  window.siteLang = function(){ return CUR; };

  function init(){
    var wrap=document.getElementById('langBtns');
    if(wrap) wrap.addEventListener('click',function(e){
      var b=e.target.closest('button[data-lang]'); if(!b) return;
      window.setSiteLang(b.getAttribute('data-lang'));
    });
    var saved=null;
    try{ saved=localStorage.getItem('la_site_lang'); }catch(e){}
    window.setSiteLang((saved==='en'||saved==='fr') ? saved : 'ar');
  }
  if(document.readyState==='loading') document.addEventListener('DOMContentLoaded',init); else init();
})();
