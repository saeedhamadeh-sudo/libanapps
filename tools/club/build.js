// ============================================================
//  بناء صفحات برنامج النوادي (club)
//  المصدر: tools/club/src/*.html + common.css + common.js + qr.js
//  الناتج: public/club-admin.html · public/club.html · public/club-door.html
//  (الكود المشترك بينحط جوّا كل صفحة — بدون ملفات خارجية)
//
//  التشغيل:  node tools/club/build.js
//  ملاحظة: عدّل ملفات src فقط، مش ملفات public مباشرة.
// ============================================================
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, 'src');
const OUT = path.join(__dirname, '..', '..', 'public');
const read = (f) => fs.readFileSync(path.join(SRC, f), 'utf8');

const css = read('common.css');
const qr = read('qr.js');
const common = read('common.js');

for (const page of ['club-admin.html', 'club.html', 'club-door.html']) {
  let html = read(page);
  for (const [mark, val] of [['/*@@CSS@@*/', css], ['/*@@QR@@*/', qr], ['/*@@COMMON@@*/', common]]) {
    if (!html.includes(mark)) throw new Error(page + ': missing ' + mark);
    html = html.split(mark).join(val);
  }
  html = html.replace('<!doctype html>', '<!doctype html>\n<!-- GENERATED by tools/club/build.js — edit tools/club/src/' + page + ' -->');
  fs.writeFileSync(path.join(OUT, page), html);
  console.log('built public/' + page, (html.length / 1024).toFixed(1) + ' KB');
}
